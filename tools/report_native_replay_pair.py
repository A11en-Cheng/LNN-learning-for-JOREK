"""Relative, component-separated replay diagnostics in native storage units.

No automatic pass threshold: numerical reproducibility is not physical accuracy.
Only trusted local .pt evidence generated by capture_native_replay_pair is read.
"""
import argparse
import json
from dataclasses import fields,is_dataclass
from pathlib import Path
import numpy as np
import torch
from tools.native_replay_metrics import compare_cloud,relative_metrics

FIELDS=('psi','Phi','Z_j','omega','rho','T_i','v_par','rho_imp','T_e')
CHANNELS=('dE_ion','rad_sink','Z_eff','Z_imp','N_imp')


def compare_tree(reference,candidate):
    """Compare diagnostic caches without conflating their physical dimensions."""
    if reference is None or candidate is None:
        return dict(exact=reference is None and candidate is None)
    if isinstance(reference,np.ndarray):
        if reference.shape!=np.shape(candidate):return dict(shape_equal=False)
        if np.issubdtype(reference.dtype,np.floating):return relative_metrics(reference,candidate)
        return dict(exact=bool(np.array_equal(reference,candidate)),changed=int(np.count_nonzero(reference!=candidate)))
    if is_dataclass(reference):
        return {f.name:compare_tree(getattr(reference,f.name),getattr(candidate,f.name)) for f in fields(reference)}
    if isinstance(reference,dict):
        return dict(keys_equal=reference.keys()==candidate.keys(),
            values={k:compare_tree(v,candidate[k]) for k,v in reference.items() if k in candidate})
    if isinstance(reference,(tuple,list)):
        return dict(length_equal=len(reference)==len(candidate),
            values=[compare_tree(a,b) for a,b in zip(reference,candidate)])
    if isinstance(reference,(float,np.floating)):return relative_metrics(np.asarray(reference),np.asarray(candidate))
    return dict(exact=bool(reference==candidate))


def compare_states(before,reference,candidate):
    b=before.runtime;r=reference.runtime;c=candidate.runtime
    fluid={}
    for i,name in enumerate(FIELDS):
        fluid[name]=dict(values=relative_metrics(r.fields_current[i],c.fields_current[i]),
            raw_deltas=relative_metrics(r.fluid_deltas[i],c.fluid_deltas[i]),
            observed_state_increment=relative_metrics(r.fields_current[i]-b.fields_current[i],c.fields_current[i]-b.fields_current[i]),
            degree_values=[relative_metrics(r.fields_current[i,d],c.fields_current[i,d]) for d in range(4)],
            degree_raw_deltas=[relative_metrics(r.fluid_deltas[i,d],c.fluid_deltas[i,d]) for d in range(4)])
    projection={name:dict(values=relative_metrics(r.marker.feedback.values[i],c.marker.feedback.values[i]),
        deltas=relative_metrics(r.marker.feedback.deltas[i],c.marker.feedback.deltas[i]),
        degree_values=[relative_metrics(r.marker.feedback.values[i,d],c.marker.feedback.values[i,d]) for d in range(4)])
        for i,name in enumerate(CHANNELS)}
    return dict(schema='native-component-replay-comparison-v1',
        comparison='continuous_vs_restored_same_event_NOT_JOREK_prediction_error',
        units='native_storage_no_unit_conversion_per_field_and_channel',
        acceptance_threshold=None,qualification_granted=False,
        cloud=compare_cloud(r.marker.cloud,c.marker.cloud,before=b.marker.cloud),
        fields=fluid,projection=projection,
        memory=relative_metrics(r.field_memory,c.field_memory),
        memory_increment=relative_metrics(r.field_memory-b.field_memory,c.field_memory-b.field_memory),
        transport_history=compare_tree(getattr(r.marker,'transport_history',None),getattr(c.marker,'transport_history',None)),
        shard=compare_tree(r.shards,c.shards),clock=compare_tree(r.marker.clock,c.marker.clock),
        field_time=compare_tree(r.fluid_time_si,c.fluid_time_si))


def report_directory(directory):
    before,reference,candidate=(torch.load(directory/f'{phase}.pt',weights_only=False,map_location='cpu')
        for phase in ('before_second','continuous_second','restored_second'))
    result=compare_states(before,reference,candidate)
    source_inputs=[json.loads((directory/f'{phase}-source-input.json').read_text()) for phase in ('continuous','restored')]
    result['source_input_exact']={k:source_inputs[0][k]==source_inputs[1][k] for k in source_inputs[0]}
    born=[torch.load(directory/f'{phase}-births.pt',weights_only=False,map_location='cpu') for phase in ('continuous','restored')]
    result['birth_cloud']=compare_cloud(*born)
    samples={}
    for i in range(2):
        a,b=(np.load(directory/f'{phase}-sample-{i}.npz') for phase in ('continuous','restored'))
        names=FIELDS if a['values'].shape==(9,) else CHANNELS
        samples[str(i)]={k:compare_tree(a[k],b[k]) for k in ('element','st','rz')}
        samples[str(i)]['components']={name:dict(
            coefficients=relative_metrics(a['fields'][j],b['fields'][j]),
            value=relative_metrics(a['values'][j],b['values'][j]),
            gradient_R=relative_metrics(a['gradient'][j,0],b['gradient'][j,0]),
            gradient_Z=relative_metrics(a['gradient'][j,1],b['gradient'][j,1]))
            for j,name in enumerate(names)}
    result['first_source_samples']=samples
    a,b=(np.load(directory/f'{phase}-projection.npz') for phase in ('continuous','restored'))
    result['source_projection_boundary']={k:{name:relative_metrics(a[k][i],b[k][i]) for i,name in enumerate(CHANNELS)} for k in ('rhs','values')}
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory',required=True,type=Path)
    parser.add_argument('--output',required=True,type=Path)
    args=parser.parse_args()
    if args.output.exists():raise ValueError('new evidence output required')
    result=report_directory(args.directory)
    with args.output.open('x') as f:json.dump(result,f,indent=2,allow_nan=False)
    print(args.output)


if __name__=='__main__':main()
